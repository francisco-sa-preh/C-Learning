            dtCurrency.Rows.Add("EUR", 1m);        // Euro
            dtCurrency.Rows.Add("USD", 1.08m);     // US Dollar
            dtCurrency.Rows.Add("GBP", 0.86m);     // British Pound
            dtCurrency.Rows.Add("JPY", 162.50m);   // Japanese Yen
            dtCurrency.Rows.Add("CHF", 0.94m);     // Swiss Franc
            dtCurrency.Rows.Add("CAD", 1.48m);     // Canadian Dollar
            dtCurrency.Rows.Add("AUD", 1.66m);     // Australian Dollar
            dtCurrency.Rows.Add("NZD", 1.79m);     // New Zealand Dollar
            dtCurrency.Rows.Add("CNY", 7.83m);     // Chinese Yuan
            dtCurrency.Rows.Add("SEK", 11.10m);    // Swedish Krona
            dtCurrency.Rows.Add("NOK", 11.75m);    // Norwegian Krone
            dtCurrency.Rows.Add("DKK", 7.46m);     // Danish Krone
            dtCurrency.Rows.Add("PLN", 4.32m);     // Polish Zloty
            dtCurrency.Rows.Add("CZK", 24.90m);    // Czech Koruna
            dtCurrency.Rows.Add("HUF", 398.00m);   // Hungarian Forint
            dtCurrency.Rows.Add("BRL", 6.20m);     // Brazilian Real
            dtCurrency.Rows.Add("MXN", 20.50m);    // Mexican Peso
